#!/usr/bin/env python3
"""Offline, deterministic data audit.

  .venv/bin/python scripts/audit_data.py                    # run all checks; write data/audit_report.md, data/audit_results.json, docs/DATA_STATUS.md
  .venv/bin/python scripts/audit_data.py --status-only      # only regenerate docs/DATA_STATUS.md from data/catalog.csv
  .venv/bin/python scripts/audit_data.py --update-catalog   # also set AUTO_CHECKED/verified_by/verified_on for datasets whose checks passed
  .venv/bin/python scripts/audit_data.py --live             # optional OSM node/way checks (network; skipped cleanly if unavailable)
  .venv/bin/python scripts/audit_data.py --deep             # hash the large private files byte by byte (slow)

Exit code 1 when any check fails. Never modifies a data file. LIVE_CHECKED is never set automatically.
"""
from __future__ import annotations

import argparse
import datetime
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from data_audit import checks, status  # noqa: E402
from data_audit.common import ROOT, read_catalog, write_catalog  # noqa: E402


def run(root: Path = ROOT, live: bool = False, deep: bool = False) -> list[dict]:
    cat = read_catalog(root / "data" / "catalog.csv")
    cfg = checks.load_config(root)
    out = []
    for fn in checks.ALL:
        try:
            out.append(fn(cat, root=root, cfg=cfg, live=live, deep=deep))
        except Exception as exc:  # a crashing check is a failed check, not a silent pass
            out.append(checks.result(fn.__name__, fn.__name__, "fail", [], f"check crashed: {type(exc).__name__}: {exc}"))
    return out


def render_report(results: list[dict]) -> str:
    icon = {"pass": "PASS", "fail": "FAIL", "warn": "WARN", "skip": "SKIP"}
    L = ["# Data audit report", "", "Generated by `scripts/audit_data.py` (offline, deterministic). Rerun after any data change.", "",
         "| # | Check | Result | Summary |", "| --- | --- | --- | --- |"]
    for r in results:
        L.append(f"| {r['id']} | {r['title']} | **{icon[r['status']]}** | {r['summary']} |")
    for r in results:
        L += ["", f"## Check {r['id']}: {r['title']} — {icon[r['status']]}", "", r["summary"], ""]
        L += [f"- {d}" for d in r["details"]]
    L.append("")
    return "\n".join(L)


def update_catalog(results: list[dict], root: Path = ROOT) -> list[str]:
    """AUTO_CHECKED only for UNVERIFIED datasets with check 1 passed for them and a content check that passed and none failed."""
    cat = read_catalog(root / "data" / "catalog.csv")
    structural = {"0", "1", "2"}
    failed_ids = {d for r in results if r["status"] == "fail" for d in r["datasets"]}
    check1 = next((r for r in results if r["id"] == "1"), None)
    ok1 = set(check1["data"].get("verified", [])) if check1 else set()
    passed = {}
    for r in results:
        if r["status"] == "pass" and r["id"] not in structural:
            for d in r["datasets"]:
                passed.setdefault(d, []).append(r["id"])
    alias = {"ferry_stops": "ferry_stops", "health_facilities": "health_facilities"}
    changed = []
    today = datetime.date.today().isoformat()
    for row in cat:
        d = row["dataset_id"]
        if row["verification_status"] == "UNVERIFIED" and d in ok1 and d in passed and d not in failed_ids:
            row["verification_status"] = "AUTO_CHECKED"
            row["verified_by"] = "scripts/audit_data.py (checks " + ",".join(sorted(passed[d])) + ")"
            row["verified_on"] = today
            changed.append(d)
    write_catalog(cat, root / "data" / "catalog.csv")
    return changed


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--status-only", action="store_true")
    ap.add_argument("--update-catalog", action="store_true")
    ap.add_argument("--live", action="store_true")
    ap.add_argument("--deep", action="store_true")
    args = ap.parse_args(argv)
    if args.status_only:
        print(f"wrote {status.write().relative_to(ROOT)}")
        return 0
    results = run(ROOT, args.live, args.deep)
    (ROOT / "data" / "audit_results.json").write_text(json.dumps(results, indent=1, sort_keys=True, ensure_ascii=False) + "\n", encoding="utf-8")
    (ROOT / "data" / "audit_report.md").write_text(render_report(results), encoding="utf-8")
    if args.update_catalog:
        print("AUTO_CHECKED:", ", ".join(update_catalog(results)) or "none")
    print(f"wrote {status.write().relative_to(ROOT)}")
    for r in results:
        print(f"[{r['status'].upper():4}] {r['id']} {r['title']}: {r['summary']}")
    return 1 if any(r["status"] == "fail" for r in results) else 0


if __name__ == "__main__":
    raise SystemExit(main())

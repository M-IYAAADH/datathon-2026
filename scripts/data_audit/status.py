"""Regenerate docs/DATA_STATUS.md from data/catalog.csv (and the organiser log)."""
from __future__ import annotations

import re
from collections import Counter
from pathlib import Path

from .common import MISSING_MARK, ROOT, read_catalog


def _cell(s: str, n: int = 160) -> str:
    s = (s or "").replace("|", "/").replace("\n", " ")
    return s if len(s) <= n else s[: n - 1] + "…"


def open_questions(root: Path = ROOT) -> list[tuple[str, str]]:
    p = root / "data" / "organiser_answers.md"
    if not p.exists():
        return []
    out = []
    for line in p.read_text(encoding="utf-8").splitlines():
        m = re.match(r"\|\s*(Q\d+)\s*\|\s*OPEN\s*\|\s*(.*?)\s*\|", line)
        if m:
            out.append((m.group(1), m.group(2)))
    return out


def render(cat: list[dict], root: Path = ROOT) -> str:
    L = ["# Data status", "", "Generated by `.venv/bin/python scripts/audit_data.py --status-only` from `data/catalog.csv`. Do not edit by hand: edit the catalogue and regenerate.", ""]
    by_v = Counter(r["verification_status"] for r in cat)
    by_s = Counter(r["status"] for r in cat)
    miss = [r for r in cat if r["sha256"] == MISSING_MARK]
    L += [f"{len(cat)} datasets. Status: " + ", ".join(f"{k} {v}" for k, v in sorted(by_s.items())) + ". Verification: " + ", ".join(f"{k} {v}" for k, v in sorted(by_v.items())) + f". MISSING: {len(miss)}.", ""]
    L += ["| dataset_id | status | verification_status | owner | blockers | next action |", "| --- | --- | --- | --- | --- | --- |"]
    for r in cat:
        st = r["status"] + (" (MISSING)" if r["sha256"] == MISSING_MARK else "")
        L.append(f"| `{r['dataset_id']}` | {st} | {r['verification_status']} | {_cell(r['owner'], 60)} | {_cell(r['blockers'])} | {_cell(r['next_action'])} |")
    L += ["", "## What blocks the planner", ""]
    qs = open_questions(root)
    L.append("### Missing datasets")
    for r in miss:
        L.append(f"- `{r['dataset_id']}` (`{r['path']}`): {_cell(r['blockers'] or r['known_issues'])}")
    L += ["", "### Open organiser questions", ""]
    for q, t in qs:
        deps = [r["dataset_id"] for r in cat if f"({q}" in r["blockers"] or f", {q}" in r["blockers"] or f"{q})" in r["blockers"]]
        L.append(f"- **{q}** {_cell(t, 200)}" + (f" Blocks: {', '.join('`'+d+'`' for d in deps)}." if deps else ""))
    L += ["", "### Datasets waiting on an organiser answer", ""]
    for r in cat:
        if r["verification_status"] == "NEEDS_ORGANISER":
            L.append(f"- `{r['dataset_id']}`: {_cell(r['blockers'])}")
    L += ["", "### Not yet verified by anything but existence", ""]
    unv = [r["dataset_id"] for r in cat if r["verification_status"] == "UNVERIFIED" and r["sha256"] != MISSING_MARK and r["status"] != "deprecated"]
    L.append(", ".join(f"`{d}`" for d in unv) or "none")
    L += ["", "### Deprecated (do not use in the app)", ""]
    L += [f"- `{r['dataset_id']}`: {_cell(r['known_issues'])}" for r in cat if r["status"] == "deprecated"]
    L.append("")
    return "\n".join(L)


def write(root: Path = ROOT) -> Path:
    out = root / "docs" / "DATA_STATUS.md"
    out.write_text(render(read_catalog(root / "data" / "catalog.csv"), root), encoding="utf-8")
    return out
